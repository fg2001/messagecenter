import { setTimeout as delay } from 'node:timers/promises'

const config = {
  action: process.argv[2] ?? 'help',
  total: Number(process.env.LOAD_TOTAL ?? 1000),
  concurrency: Number(process.env.LOAD_CONCURRENCY ?? 100),
  novuBaseUrl: process.env.NOVU_BASE_URL ?? 'http://192.168.124.2:13000',
  messageCenterBaseUrl: process.env.MESSAGE_CENTER_BASE_URL ?? 'http://127.0.0.1:5000',
  keycloakTokenUrl: process.env.KEYCLOAK_TOKEN_URL
    ?? 'http://192.168.124.2:18085/realms/master/protocol/openid-connect/token',
  clientId: process.env.KEYCLOAK_CLIENT_ID ?? 'cooper',
  clientSecret: required('KEYCLOAK_CLIENT_SECRET'),
  username: process.env.KEYCLOAK_USERNAME ?? '196045',
  password: required('KEYCLOAK_PASSWORD'),
  novuApiKey: required('NOVU_API_KEY'),
  subscriberId: process.env.LOAD_SUBSCRIBER_ID ?? '196045',
  requestTimeoutMs: Number(process.env.LOAD_REQUEST_TIMEOUT_MS ?? 30000),
  progressEvery: Number(process.env.LOAD_PROGRESS_EVERY ?? 1000),
}

function required(name) {
  const value = process.env[name]
  if (!value) throw new Error(`${name} is required`)
  return value
}

function percentile(sorted, ratio) {
  if (!sorted.length) return 0
  return sorted[Math.min(sorted.length - 1, Math.floor(sorted.length * ratio))]
}

async function request(url, options = {}) {
  const controller = new AbortController()
  const timer = setTimeout(() => controller.abort(), config.requestTimeoutMs)
  try {
    return await fetch(url, { ...options, signal: controller.signal })
  } finally {
    clearTimeout(timer)
  }
}

let serviceToken = { value: '', expiresAt: 0 }
let userToken = { value: '', expiresAt: 0 }
let serviceTokenRequest
let userTokenRequest

async function acquireToken(grantType) {
  const isService = grantType === 'client_credentials'
  const cache = isService ? serviceToken : userToken
  if (cache.value && Date.now() < cache.expiresAt - 30_000) return cache.value
  const inFlight = isService ? serviceTokenRequest : userTokenRequest
  if (inFlight) return inFlight

  const tokenRequest = (async () => {
    const body = new URLSearchParams({
      grant_type: grantType,
      client_id: config.clientId,
      client_secret: config.clientSecret,
    })
    if (!isService) {
      body.set('username', config.username)
      body.set('password', config.password)
    }

    const response = await request(config.keycloakTokenUrl, {
      method: 'POST',
      headers: { 'content-type': 'application/x-www-form-urlencoded' },
      body,
    })
    if (!response.ok) throw new Error(`Token request failed: ${response.status}`)
    const data = await response.json()
    cache.value = data.access_token
    cache.expiresAt = Date.now() + Number(data.expires_in ?? 300) * 1000
    return cache.value
  })()

  if (isService) serviceTokenRequest = tokenRequest
  else userTokenRequest = tokenRequest

  try {
    return await tokenRequest
  } finally {
    if (isService) serviceTokenRequest = undefined
    else userTokenRequest = undefined
  }
}

function sendPayload(index) {
  const id = `LOAD-${Date.now()}-${index}`
  return {
    businessType: 'novu_extreme_load',
    businessId: id,
    title: `Extreme load ${index}`,
    content: `Generated by controlled load test ${id}`,
    url: `/load/${id}`,
    receivers: [{ type: 'user', id: config.subscriberId }],
  }
}

async function sendDirect(index) {
  const payload = sendPayload(index)
  return request(`${config.novuBaseUrl}/v1/events/trigger`, {
    method: 'POST',
    headers: {
      authorization: `ApiKey ${config.novuApiKey}`,
      'content-type': 'application/json',
    },
    body: JSON.stringify({
      name: 'system-notification',
      to: { subscriberId: config.subscriberId },
      payload,
    }),
  })
}

async function sendWrapper(index) {
  const token = await acquireToken('client_credentials')
  return request(`${config.messageCenterBaseUrl}/api/message-center/send`, {
    method: 'POST',
    headers: {
      authorization: `Bearer ${token}`,
      'content-type': 'application/json',
    },
    body: JSON.stringify(sendPayload(index)),
  })
}

async function fetchMessageIds(limit) {
  const ids = []
  let page = 0
  while (ids.length < limit) {
    const url = new URL('/v1/messages', config.novuBaseUrl)
    url.searchParams.set('page', String(page))
    url.searchParams.set('limit', '100')
    url.searchParams.set('pageSize', '100')
    url.searchParams.set('subscriberId', config.subscriberId)
    const response = await request(url, {
      headers: { authorization: `ApiKey ${config.novuApiKey}` },
    })
    if (!response.ok) throw new Error(`Fetch messages failed: ${response.status}`)
    const envelope = await response.json()
    const messages = envelope.data ?? []
    ids.push(...messages.map((message) => message._id ?? message.id).filter(Boolean))
    if (!envelope.hasMore || messages.length === 0) break
    page++
  }
  return ids.slice(0, limit)
}

async function markRead(messageId) {
  const token = await acquireToken('password')
  return request(
    `${config.messageCenterBaseUrl}/api/message-center/messages/${encodeURIComponent(messageId)}/read`,
    {
      method: 'POST',
      headers: { authorization: `Bearer ${token}` },
    },
  )
}

async function runLoad(operation, total) {
  let next = 0
  let completed = 0
  const statuses = new Map()
  const latencies = []
  const startedAt = performance.now()

  async function worker() {
    while (true) {
      const index = next++
      if (index >= total) return
      const requestStartedAt = performance.now()
      let status = 'exception'
      try {
        const response = await operation(index)
        status = String(response.status)
        await response.body?.cancel()
      } catch (error) {
        status = error?.name === 'AbortError' ? 'timeout' : 'exception'
      }
      latencies.push(performance.now() - requestStartedAt)
      statuses.set(status, (statuses.get(status) ?? 0) + 1)
      completed++
      if (completed % config.progressEvery === 0 || completed === total) {
        const seconds = (performance.now() - startedAt) / 1000
        process.stdout.write(
          `progress=${completed}/${total} rate=${(completed / seconds).toFixed(1)}/s statuses=${JSON.stringify(Object.fromEntries(statuses))}\n`,
        )
      }
    }
  }

  await Promise.all(Array.from({ length: config.concurrency }, worker))
  const elapsedSeconds = (performance.now() - startedAt) / 1000
  latencies.sort((a, b) => a - b)
  console.log(JSON.stringify({
    action: config.action,
    total,
    concurrency: config.concurrency,
    elapsedSeconds: Number(elapsedSeconds.toFixed(3)),
    throughputPerSecond: Number((total / elapsedSeconds).toFixed(2)),
    statuses: Object.fromEntries(statuses),
    latencyMs: {
      p50: Number(percentile(latencies, 0.50).toFixed(1)),
      p95: Number(percentile(latencies, 0.95).toFixed(1)),
      p99: Number(percentile(latencies, 0.99).toFixed(1)),
      max: Number((latencies.at(-1) ?? 0).toFixed(1)),
    },
  }))
}

switch (config.action) {
  case 'send-direct':
    await runLoad(sendDirect, config.total)
    break
  case 'send-wrapper':
    await runLoad(sendWrapper, config.total)
    break
  case 'read': {
    const ids = await fetchMessageIds(config.total)
    console.log(`loaded_message_ids=${ids.length}`)
    await runLoad((index) => markRead(ids[index % ids.length]), config.total)
    break
  }
  case 'wait-count': {
    const expected = config.total
    for (;;) {
      const ids = await fetchMessageIds(expected)
      console.log(`message_count_at_least=${ids.length} expected=${expected}`)
      if (ids.length >= expected) break
      await delay(5000)
    }
    break
  }
  default:
    console.log('Usage: node scripts/novu-extreme-load.mjs send-direct|send-wrapper|read|wait-count')
}
